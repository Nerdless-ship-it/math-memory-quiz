// 立方体截面图 —— 考公「图形推理 · 截面图」题库（24 题，4 选 1）。
//
// ── 几何模型（与 docs/ARCHITECTURE.md 第 7.4 节、qa-output/geometry-feasibility.mjs 一致）──
//   立方体 = [-1,1]³（棱长 2、中心在原点），平面 = { x | n·x = d }。
//   平面与**实心**立方体的交是凸多边形，边数只可能是 3~6：
//   立方体只有 6 个面，平面最多与 6 个面各交出一条边 ⇒ 截面最多 6 边形 ⇒ **七边形不可能**。
//
//   本文件的「不可能」选项一律用「平面与立方体完全没有交点」的参数表达，判定依据是
//   一条可验算的不等式（不是感觉）：
//       对立方体上任意点 x 都有 |n·x| ≤ |n₁|+|n₂|+|n₃| = L，
//       故当 |d| > L 时集合 { x | n·x = d } 与立方体无公共点，
//       cubeSection(n, d) 返回 0 个交点 ⇒ 该平面截不出任何截面。
//   每题注释里都写明了这一条（L 的值、d 的值、为什么 d 出界）——见各题「不可能是」那一项。
//   ⚠️ 立方体只有 6 个面，所以**不存在**能画出七边形的参数：七边形在几何上不成立，
//      任何 planeNormal/d 都无法给出 7 条边，这一点由 test/cross-section.test.mjs 显式断言。
//
// ── 出题与校验约定 ────────────────────────────────────────────────
//   1. 每题 4 个选项：3 个「确实可能」的截面 + **恰好 1 个**「不可能」（= 答案，back 指向它）。
//   2. 3 个「可能」选项的**边数互不相同**（三角形/四边形/五边形/六边形里取 3 种），
//      因此不会出现「三个都是正方形」这种同构敷衍；同一题内 4 个平面也互不相同。
//   3. 24 题按边数组合各 6 题：{3,4,5} / {3,4,6} / {3,5,6} / {4,5,6}；
//      答案位置 6 题 A、6 题 B、6 题 C、6 题 D（见各题 back）。
//   4. 全部参数都经 test/cross-section.test.mjs 用 public/js/geometry.js 的
//      cubeSection / sectionSideCount / sectionName 逐条实测：
//      可能项 ≥3 交点且边数 ∈{3,4,5,6}，不可能项 0 交点 —— 任何一项不成立测试即红。
//
// ── 题干图形：只画「一个完整的立方体」，不画具体截面 ────────────────────
//   本题问的是「对这个立方体而言，**任意**平面截出来的截面不可能是哪个形状」。
//   因此题干刻意不画任何一道具体截面（figure.spec 的 |d| 超出 n·x 的取值范围 ⇒
//   cubeSection 返回 0 点 ⇒ figure.js 只画立方体的面与棱）：
//   若题干画出一道具体截面（例如正六边形），学生就会把题干上那个截面当成已知条件 ——
//   题目立刻变得不可解（答案取决于选项里有没有六边形），这是必须避免的陷阱。
//   真题的截面图题干也就是一个立方体。
//
//   题干 24 条**完全相同**，题目身份落在选项组合上：注册表里该科声明了
//   `allowDuplicateFront: true` + `uniqueBy: 'choices'`（subjects.test.mjs 用
//   choiceFigures 的 JSON 判定「是否真的重复出题」）。test/cross-section.test.mjs
//   同时断言：24 条题干一致 **且** 24 组 choiceFigures 互不相同 —— 两条缺一不可。

